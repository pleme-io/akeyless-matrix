/// A source-only builds file (packages with `builder = none`): each
/// release exposes its source, version and metadata, and no derivation.
fn source_only_builds(matrix: &Matrix, language: Language, first_line: &str) -> String {
    let body = release_entries(
        matrix,
        |p| p.language == language,
        |pkg, rel| {
            attrs(
                [
                    inherit(Some(source(&rel.src_key)), ["src"]),
                    entry("version", source_version(&rel.src_key)),
                ]
                .into_iter()
                .chain(description_homepage(pkg)),
            )
        },
    );
    nix_file(
        &[
            first_line,
            AUTO_GENERATED,
            "Source-only (no Nix builder yet).",
        ],
        &["sources"],
        block(body),
    )
}

/// Generate the `builds/ruby/default.nix` file content from the matrix.
/// Ruby packages currently use builder = none, so this emits source-only outputs.
#[must_use]
pub fn generate_ruby_builds(matrix: &Matrix) -> String {
    source_only_builds(
        matrix,
        Language::Ruby,
        "Ruby package sources for akeyless repos.",
    )
}

