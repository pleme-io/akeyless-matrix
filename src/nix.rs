/// `name: args: <builder> pkgs ({ <defaults> } // args)`: the shared-defaults
/// wrapper every Go package entry is applied through.
fn go_defaults_wrapper(builder: &str, defaults: Vec<AttrSetEntry>) -> NixValue {
    NixValue::lambda_single(
        "name",
        NixValue::lambda_single(
            "args",
            call(
                NixValue::ident(builder),
                [
                    NixValue::ident("pkgs"),
                    NixValue::BinOp {
                        op: NixBinOp::Update,
                        left: Box::new(attrs(defaults)),
                        right: Box::new(NixValue::ident("args")),
                    },
                ],
            ),
        ),
    )
}

/// `version = v name; src = sources.${name};`
fn go_version_and_src() -> [AttrSetEntry; 2] {
    [
        entry(
            "version",
            call(NixValue::ident("v"), [NixValue::ident("name")]),
        ),
        entry(
            "src",
            NixValue::select(
                NixValue::ident("sources"),
                [AttrKey::Interp(NixValue::ident("name"))],
            ),
        ),
    ]
}

fn go_let_bindings() -> Vec<LetBinding> {
    let tool_defaults: Vec<AttrSetEntry> = go_version_and_src()
        .into_iter()
        .chain([
            entry("doCheck", NixValue::Bool(false)),
            entry("license", nix_license("asl20")),
            AttrSetEntry::Comment(
                "Upstream go.mod is not ours to edit, so rewrite a bare-minor `go 1.N`".into(),
            ),
            AttrSetEntry::Comment(
                "to `go 1.N.0` at build time instead of tracing the fix on every eval.".into(),
            ),
            entry("normalizeGoDirective", NixValue::Bool(true)),
        ])
        .collect();
    let lib_check_defaults: Vec<AttrSetEntry> = go_version_and_src()
        .into_iter()
        .chain([entry("license", nix_license("asl20"))])
        .collect();

    vec![
        LetBinding::Comment("Version helper \u{2014} reads from source registry metadata".into()),
        bind(
            "v",
            NixValue::lambda_single(
                "name",
                NixValue::select(
                    NixValue::ident("sources"),
                    [
                        AttrKey::Interp(NixValue::ident("name")),
                        AttrKey::Ident("meta".into()),
                        AttrKey::Ident("version".into()),
                    ],
                ),
            ),
        ),
        LetBinding::Blank,
        LetBinding::Comment("Shared defaults for all akeyless Go tools".into()),
        bind(
            "mkAkeylessTool",
            go_defaults_wrapper("mkGoTool", tool_defaults),
        ),
        LetBinding::Blank,
        LetBinding::Comment("Shared defaults for all akeyless Go library checks".into()),
        bind(
            "mkAkeylessLibCheck",
            go_defaults_wrapper("mkGoLibraryCheck", lib_check_defaults),
        ),
    ]
}

/// Generate the `builds/go/default.nix` file content from the matrix.
#[must_use]
pub fn generate_go_builds(matrix: &Matrix) -> String {
    let tiers: [(u8, &str); 3] = [
        (1, "Tier 1: Daily tools"),
        (2, "Tier 2: Dev tools"),
        (
            3,
            "Tier 2/3: Libraries (build check via substrate mkGoLibraryCheck)",
        ),
    ];

    let mut body = Vec::new();
    for (tier_num, tier_label) in tiers {
        let in_tier = |p: &Package| {
            p.language == Language::Go
                && if tier_num == 3 {
                    // Tier 3 section includes library checks from tier 2 and 3
                    (p.tier == 2 || p.tier == 3) && p.builder == Builder::MkGoLibraryCheck
                } else {
                    p.tier == tier_num && p.builder == Builder::MkGoTool
                }
        };
        let entries = release_entries(matrix, in_tier, |pkg, rel| {
            if pkg.builder == Builder::MkGoTool {
                go_tool_entry(pkg, rel)
            } else {
                go_lib_check_entry(pkg, rel)
            }
        });
        if entries.is_empty() {
            continue;
        }
        body.push(AttrSetEntry::Comment(tier_rule(tier_label)));
        body.push(AttrSetEntry::Blank);
        body.extend(entries);
    }

    nix_file(
        &[
            "All Go package builds for akeyless repos.",
            AUTO_GENERATED,
            "Tools use substrate's mkGoTool. Libraries use substrate's mkGoLibraryCheck.",
        ],
        &["pkgs", "sources", "mkGoTool", "mkGoLibraryCheck"],
        NixValue::let_laid_out(LetLayout::BodyAfterIn, go_let_bindings(), block(body)),
    )
}

/// `pname`, `vendorHash` and (when set) `proxyVendor`: the head every Go
/// entry shares.
fn go_entry_head(pkg: &Package, rel: &Release) -> Vec<AttrSetEntry> {
    let mut entries = vec![
        entry("pname", s(&rel.attr_name)),
        entry(
            "vendorHash",
            rel.entry.vendor_hash.as_deref().map_or(NixValue::Null, s),
        ),
    ];
    if pkg.proxy_vendor.unwrap_or(false) {
        entries.push(entry("proxyVendor", NixValue::Bool(true)));
    }
    entries
}

fn go_tool_entry(pkg: &Package, rel: &Release) -> NixValue {
    let mut entries = go_entry_head(pkg, rel);
    if let Some(sp) = &pkg.sub_packages {
        entries.push(entry(
            "subPackages",
            NixValue::list_laid_out(CollectionLayout::Inline, sp.iter().map(|p| s(p))),
        ));
    }
    entries.extend(description_homepage(pkg));
    if let Some(lic) = &pkg.license {
        entries.push(entry("license", nix_license(license_to_nix(lic))));
    }
    if let Some(epi) = &pkg.extra_post_install {
        entries.push(entry("extraPostInstall", post_install(epi, &rel.src_key)));
    }
    call(
        NixValue::ident("mkAkeylessTool"),
        [s(&rel.src_key), attrs(entries)],
    )
}

/// `extra_post_install` as an indented string, each `${version}` becoming
/// an interpolation of this release's version, `${v "<key>"}`.
fn post_install(script: &str, src_key: &str) -> NixValue {
    let version = || call(NixValue::ident("v"), [s(src_key)]);
    NixValue::IndentedInterpolatedStr(
        script
            .lines()
            .map(|line| {
                let mut parts = Vec::new();
                for (i, literal) in line.split("${version}").enumerate() {
                    if i > 0 {
                        parts.push(StrPart::Interp(version()));
                    }
                    if !literal.is_empty() {
                        parts.push(StrPart::Literal(literal.to_string()));
                    }
                }
                parts
            })
            .collect(),
    )
}

fn go_lib_check_entry(pkg: &Package, rel: &Release) -> NixValue {
    let mut entries = go_entry_head(pkg, rel);
    entries.extend(description_homepage(pkg));
    call(
        NixValue::ident("mkAkeylessLibCheck"),
        [s(&rel.src_key), attrs(entries)],
    )
}

