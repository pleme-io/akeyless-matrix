//! The Nix files `generate` writes into blackmatter-akeyless.
//!
//! Every file is a typed [`gen_nix::NixValue`] tree rendered by gen-nix's
//! one pretty-printer; no Nix syntax is assembled from strings here. The
//! layout siblings (`LaidOut*`, comments, blank entries) exist so the
//! rendered files keep the hand-tuned shape reviewers read.

use gen_nix::{
    AttrKey, AttrSetEntry, CollectionLayout, LambdaLayout, LetBinding, LetLayout, NixBinOp,
    NixValue, StrPart, bind, destructured, entry, inherit, render_file, str_entry,
};

use crate::matrix::{Builder, Language, Matrix, Package, VersionEntry};

/// Second header line of every generated file.
const AUTO_GENERATED: &str =
    "!! AUTO-GENERATED by akeyless-matrix generate \u{2014} do not edit manually !!";

// ---------------------------------------------------------------------------
// Shared shapes
// ---------------------------------------------------------------------------

/// One verified version of a package, with the attribute and source-key
/// names it is published under: the latest verified version takes the bare
/// names, older ones a `-<sanitized version>` suffix.
struct Release<'a> {
    pkg_name: &'a str,
    version: &'a str,
    entry: &'a VersionEntry,
    attr_name: String,
    src_key: String,
}

fn releases<'a>(pkg_name: &'a str, pkg: &'a Package) -> Vec<Release<'a>> {
    let latest = Matrix::latest_verified(pkg).map(|(v, _)| v);
    let base_key = Matrix::source_key(pkg_name);
    Matrix::all_verified(pkg)
        .into_iter()
        .map(|(version, entry)| {
            let (attr_name, src_key) = if latest == Some(version) {
                (pkg_name.to_string(), base_key.clone())
            } else {
                let san = Matrix::sanitize_version(version);
                (format!("{pkg_name}-{san}"), format!("{base_key}-{san}"))
            };
            Release {
                pkg_name,
                version,
                entry,
                attr_name,
                src_key,
            }
        })
        .collect()
}

/// A whole generated file: header comments, then a function over
/// `params` whose body starts on the next line.
fn nix_file(header: &[&str], params: &[&str], body: NixValue) -> String {
    render_file(&NixValue::commented(
        header.iter().copied(),
        NixValue::lambda_laid_out(
            LambdaLayout::BodyOnNextLine,
            destructured(params.iter().copied(), false),
            body,
        ),
    ))
}

/// Attrset with one entry per line, `{` newline `}` when empty.
fn block(entries: impl IntoIterator<Item = AttrSetEntry>) -> NixValue {
    NixValue::attrset_laid_out(CollectionLayout::Block, entries)
}

/// The canonical (block) attrset over typed entries.
fn attrs(entries: impl IntoIterator<Item = AttrSetEntry>) -> NixValue {
    NixValue::AttrSet {
        recursive: false,
        entries: entries.into_iter().collect(),
    }
}

fn s(value: &str) -> NixValue {
    NixValue::str(value)
}

fn path(parts: &[&str]) -> NixValue {
    NixValue::attr_path(parts.iter().copied())
}

fn call(func: NixValue, args: impl IntoIterator<Item = NixValue>) -> NixValue {
    NixValue::apply(func, args)
}

fn nix_license(attr: &str) -> NixValue {
    path(&["pkgs", "lib", "licenses", attr])
}

/// `sources.<key>.meta.version`
fn source_version(src_key: &str) -> NixValue {
    path(&["sources", src_key, "meta", "version"])
}

/// `sources.<key>`
fn source(src_key: &str) -> NixValue {
    path(&["sources", src_key])
}

/// `── <label> ────…─` section rule, padded to a fixed width.
fn tier_rule(label: &str) -> String {
    format!(
        "\u{2500}\u{2500} {label} \u{2500}{}\u{2500}",
        "\u{2500}".repeat(50usize.saturating_sub(label.len()))
    )
}

/// `name = value;` followed by an empty line: the per-package spacing of
/// every builds file.
fn spaced(name: &str, value: NixValue) -> [AttrSetEntry; 2] {
    [entry(name, value), AttrSetEntry::Blank]
}

/// Every verified release of every package `keep` selects, as spaced
/// entries built by `build`.
fn release_entries(
    matrix: &Matrix,
    keep: impl Fn(&Package) -> bool,
    build: impl Fn(&Package, &Release) -> NixValue,
) -> Vec<AttrSetEntry> {
    matrix
        .packages
        .iter()
        .filter(|(_, pkg)| keep(pkg))
        .flat_map(|(pkg_name, pkg)| {
            releases(pkg_name, pkg)
                .into_iter()
                .flat_map(|rel| spaced(&rel.attr_name, build(pkg, &rel)))
                .collect::<Vec<_>>()
        })
        .collect()
}

fn description_homepage(pkg: &Package) -> [AttrSetEntry; 2] {
    [
        entry("description", s(&pkg.description)),
        entry("homepage", s(&pkg.homepage)),
    ]
}

/// `meta = { description; homepage; license = asl20; }`
fn asl20_meta(pkg: &Package) -> AttrSetEntry {
    entry(
        "meta",
        attrs(
            description_homepage(pkg)
                .into_iter()
                .chain([entry("license", nix_license("asl20"))]),
        ),
    )
}

/// A literal-only indented string, one element per line.
fn indented(lines: &[String]) -> NixValue {
    NixValue::IndentedInterpolatedStr(
        lines
            .iter()
            .map(|l| vec![StrPart::Literal(l.clone())])
            .collect(),
    )
}

