/// Generate the `lib/sources.nix` file content from the matrix.
#[must_use]
pub fn generate_sources_nix(matrix: &Matrix) -> String {
    let tiers: [(u8, &str); 3] = [
        (1, "Tier 1: Daily tools"),
        (2, "Tier 2: Dev tools"),
        (3, "Tier 3: SDKs"),
    ];

    let mut repos = Vec::new();
    for (tier_num, tier_label) in tiers {
        let tier_pkgs: Vec<(&String, &Package)> = matrix
            .packages
            .iter()
            .filter(|(_, p)| p.tier == tier_num && p.builder != Builder::Fetchurl)
            .collect();
        if tier_pkgs.is_empty() {
            continue;
        }
        repos.push(AttrSetEntry::Comment(tier_rule(tier_label)));

        for (pkg_name, pkg) in tier_pkgs {
            let fork_comment = pkg
                .fork_of
                .as_ref()
                .map(|_| format!("fork: {}", pkg.fork_reason.as_deref().unwrap_or("fork")));
            for rel in releases(pkg_name, pkg) {
                let Some(source_hash) = rel.entry.source_hash.as_deref() else {
                    continue;
                };
                repos.push(entry(
                    &rel.src_key,
                    attrs([
                        AttrSetEntry::Line {
                            entries: vec![
                                entry("owner", s(&pkg.owner)),
                                entry("repo", s(&pkg.repo)),
                            ],
                            comment: fork_comment.clone(),
                        },
                        entry("rev", s(&rel.entry.rev)),
                        entry("hash", s(source_hash)),
                        entry("version", s(rel.version)),
                    ]),
                ));
            }
        }
    }

    nix_file(
        &[
            "Centralized source definitions for all buildable akeyless repos.",
            AUTO_GENERATED,
            "Uses substrate's mkSourceRegistry pattern.",
        ],
        &["mkSourceRegistry", "fetchFromGitHub"],
        call(
            NixValue::ident("mkSourceRegistry"),
            [attrs([
                inherit(None, ["fetchFromGitHub"]),
                entry("repos", block(repos)),
            ])],
        ),
    )
}

