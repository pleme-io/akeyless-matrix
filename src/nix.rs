/// Map a license string (e.g., "MPL-2.0") to a nixpkgs license attribute name.
fn license_to_nix(license: &str) -> &str {
    match license {
        "MPL-2.0" => "mpl20",
        "MIT" => "mit",
        "Apache-2.0" => "asl20",
        "BSD-3-Clause" => "bsd3",
        "GPL-3.0" => "gpl3Only",
        _ => "free",
    }
}

/// License attribute for a prebuilt binary: unfree unless declared.
fn binary_license_to_nix(license: Option<&str>) -> &str {
    match license {
        None | Some("unfree") => "unfree",
        Some("MIT") => "mit",
        Some("Apache-2.0") => "asl20",
        Some(_) => "free",
    }
}

