fn binary_entry(pkg: &Package, rel: &Release) -> NixValue {
    let attr_name = rel.attr_name.as_str();
    let binary_name = pkg.binary_name.as_deref().unwrap_or(rel.pkg_name);
    let entry_hashes = rel.entry;
    let platform_hashes = [
        ("aarch64-darwin", &entry_hashes.hash_aarch64_darwin),
        ("x86_64-darwin", &entry_hashes.hash_x86_64_darwin),
        ("x86_64-linux", &entry_hashes.hash_x86_64_linux),
        ("aarch64-linux", &entry_hashes.hash_aarch64_linux),
    ];

    // One `"<platform>" = { url; hash; };` per platform with both a URL
    // template and a hash; `{version}` in the template is this release.
    let platforms = pkg.platform_urls.iter().flat_map(|urls| {
        platform_hashes.iter().filter_map(|(plat, hash)| {
            let (template, hash) = (urls.get(*plat)?, hash.as_deref()?);
            Some(str_entry(
                *plat,
                NixValue::attrset_laid_out(
                    CollectionLayout::Inline,
                    [
                        entry("url", s(&template.replace("{version}", rel.version))),
                        entry("hash", s(hash)),
                    ],
                ),
            ))
        })
    });

    let src = NixValue::select_or(
        NixValue::ident("sources"),
        [AttrKey::Interp(NixValue::ident("system"))],
        call(
            NixValue::ident("throw"),
            [NixValue::InterpolatedStr(vec![
                StrPart::Literal(format!("{attr_name}: unsupported system ")),
                StrPart::Interp(NixValue::ident("system")),
            ])],
        ),
    );

    let derivation = attrs([
        entry("pname", s(attr_name)),
        entry("version", s(rel.version)),
        entry(
            "src",
            call(
                path(&["pkgs", "fetchurl"]),
                [NixValue::attrset_laid_out(
                    CollectionLayout::Inline,
                    [inherit(Some(NixValue::ident("src")), ["url", "hash"])],
                )],
            ),
        ),
        entry("dontUnpack", NixValue::Bool(true)),
        entry(
            "nativeBuildInputs",
            call(
                path(&["pkgs", "lib", "optionals"]),
                [
                    path(&["pkgs", "stdenv", "hostPlatform", "isLinux"]),
                    NixValue::list_laid_out(
                        CollectionLayout::Inline,
                        [path(&["pkgs", "autoPatchelfHook"])],
                    ),
                ],
            ),
        ),
        entry(
            "installPhase",
            indented(&[
                "mkdir -p $out/bin".to_string(),
                format!("cp $src $out/bin/{binary_name}"),
                format!("chmod +x $out/bin/{binary_name}"),
            ]),
        ),
        entry(
            "meta",
            attrs(description_homepage(pkg).into_iter().chain([
                entry(
                    "license",
                    nix_license(binary_license_to_nix(pkg.license.as_deref())),
                ),
                entry(
                    "platforms",
                    call(
                        path(&["builtins", "attrNames"]),
                        [NixValue::ident("sources")],
                    ),
                ),
                entry("mainProgram", s(binary_name)),
            ])),
        ),
    ]);

    NixValue::let_laid_out(
        LetLayout::BodyAfterIn,
        [bind("sources", block(platforms)), bind("src", src)],
        call(path(&["pkgs", "stdenv", "mkDerivation"]), [derivation]),
    )
}

