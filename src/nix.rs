/// Generate the `builds/rust/default.nix` file content from the matrix.
#[must_use]
pub fn generate_rust_builds(matrix: &Matrix) -> String {
    let body = release_entries(
        matrix,
        |p| p.language == Language::Rust,
        |pkg, rel| {
            let mut entries = vec![
                entry("pname", s(&rel.attr_name)),
                entry("version", source_version(&rel.src_key)),
                entry("src", source(&rel.src_key)),
            ];
            if let Some(ch) = &rel.entry.cargo_hash {
                entries.push(entry("cargoHash", s(ch)));
            }
            entries.push(entry("doCheck", NixValue::Bool(false)));
            if let Some(inputs) = &pkg.native_build_inputs {
                entries.push(entry(
                    "nativeBuildInputs",
                    NixValue::list_laid_out(
                        CollectionLayout::Inline,
                        inputs.iter().map(|i| path(&["pkgs", i])),
                    ),
                ));
            }
            entries.push(asl20_meta(pkg));
            call(
                path(&["pkgs", "rustPlatform", "buildRustPackage"]),
                [attrs(entries)],
            )
        },
    );
    nix_file(
        &["Rust package builds for akeyless repos.", AUTO_GENERATED],
        &["pkgs", "sources"],
        block(body),
    )
}

