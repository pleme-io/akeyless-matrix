/// Generate the `lib/matrix-metadata.nix` file content from the matrix.
#[must_use]
pub fn generate_matrix_metadata(matrix: &Matrix) -> String {
    // packageSourceMap: ALL versioned entries
    let mut source_map = Vec::new();
    for (pkg_name, pkg) in &matrix.packages {
        if pkg.builder == Builder::Fetchurl {
            // Binary packages use their own name as the source key, and have
            // no versioned source keys.
            if Matrix::latest_verified(pkg).is_some() {
                source_map.push(entry(pkg_name, s(pkg_name)));
            }
            continue;
        }
        for rel in releases(pkg_name, pkg) {
            source_map.push(entry(&rel.attr_name, s(&rel.src_key)));
        }
    }

    let mut body = vec![
        entry("packageSourceMap", block(source_map)),
        AttrSetEntry::Blank,
    ];
    for (tier_num, tier_name) in [
        (1, "tier1Packages"),
        (2, "tier2Packages"),
        (3, "tier3Packages"),
    ] {
        // Only packages with a buildable builder and at least one verified
        // version.
        let names = matrix
            .packages
            .iter()
            .filter(|(_, p)| {
                p.tier == tier_num
                    && p.builder != Builder::None
                    && Matrix::latest_verified(p).is_some()
            })
            .map(|(name, _)| s(name));
        body.extend(spaced(
            tier_name,
            NixValue::list_laid_out(CollectionLayout::Block, names),
        ));
    }

    render_file(&NixValue::commented(
        [
            AUTO_GENERATED,
            "Exports packageSourceMap and tier lists for flake.nix and module/default.nix.",
        ],
        block(body),
    ))
}

